import fs from 'fs';
import { Keypair, PublicKey, SystemProgram } from '@solana/web3.js';
import { payer, conn, log, program, fund, expectFail } from './lib/labcommon.mjs';
const idl = JSON.parse(fs.readFileSync(new URL('../../dapps/static/nomad-passport/idl.json', import.meta.url), 'utf8'));
const prog = program(idl);
const pid = new PublicKey(idl.address);
const agent = Keypair.generate(), stranger = Keypair.generate();
const [passport] = PublicKey.findProgramAddressSync([Buffer.from('passport'), agent.publicKey.toBuffer()], pid);
log({ step: 'setup', program: pid.toBase58(), passport: passport.toBase58(), agent: agent.publicKey.toBase58() });
await fund(stranger.publicKey, 5_000_000);
let sig = await prog.methods.initializePassport(agent.publicKey, 'lab research agent', ['read:web', 'pay:usdc<=5']).accounts({ authority: payer.publicKey, payer: payer.publicKey, passport, systemProgram: SystemProgram.programId }).rpc();
log({ step: 'initialize_passport', ok: true, sig });
sig = await prog.methods.updatePermissions('lab research agent v2', ['read:web', 'pay:usdc<=5', 'post:x']).accounts({ authority: payer.publicKey, passport }).rpc();
log({ step: 'update_permissions', ok: true, sig });
const p = await prog.account.passport.fetch(passport);
log({ step: 'state', label: p.label, permissions: p.permissions, authority: p.authority.toBase58() });
await expectFail('update_by_stranger', () => program(idl, stranger).methods.updatePermissions(null, ['admin:*']).accounts({ authority: stranger.publicKey, passport }).signers([stranger]).rpc());
await expectFail('empty_scope', () => prog.methods.updatePermissions(null, ['']).accounts({ authority: payer.publicKey, passport }).rpc());
await expectFail('label_too_long', () => prog.methods.updatePermissions('x'.repeat(65), ['read:web']).accounts({ authority: payer.publicKey, passport }).rpc());
await expectFail('close_by_stranger', () => program(idl, stranger).methods.closePassport().accounts({ authority: stranger.publicKey, passport }).signers([stranger]).rpc());
sig = await prog.methods.closePassport().accounts({ authority: payer.publicKey, passport }).rpc();
log({ step: 'close_passport', ok: true, sig, closed: (await conn.getAccountInfo(passport)) === null });
process.exit(0);
