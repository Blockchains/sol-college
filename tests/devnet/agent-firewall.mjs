import fs from 'fs';
import { Keypair, PublicKey, SystemProgram } from '@solana/web3.js';
import anchor from '@coral-xyz/anchor';
import { payer, conn, log, program, fund, expectFail, BN } from './lib/labcommon.mjs';
const idl = JSON.parse(fs.readFileSync(new URL('../../dapps/static/agent-firewall/idl.json', import.meta.url), 'utf8'));
const swapIdl = JSON.parse(fs.readFileSync(new URL('../../dapps/static/agent-firewall/mock_swap_idl.json', import.meta.url), 'utf8'));
const prog = program(idl);
const pid = new PublicKey(idl.address), swapPid = new PublicKey(swapIdl.address);
const agent = Keypair.generate(), stranger = Keypair.generate(), recipient = Keypair.generate();
await fund(agent.publicKey, 5_000_000); await fund(stranger.publicKey, 5_000_000);
const owner = Keypair.generate(); await fund(owner.publicKey, 40_000_000);
const [vault] = PublicKey.findProgramAddressSync([Buffer.from('vault'), owner.publicKey.toBuffer()], pid);
log({ step: 'setup', program: pid.toBase58(), mock_swap: swapPid.toBase58(), vault: vault.toBase58(), agent: agent.publicKey.toBase58(), recipient: recipient.publicKey.toBase58() });
const op = program(idl, owner);
let sig = await op.methods.initialize(agent.publicKey, new BN(5_000_000), swapPid).accountsPartial({ owner: owner.publicKey, vault }).signers([owner]).rpc();
log({ step: 'initialize', ok: true, sig, spend_limit: 5_000_000, allowed_target: swapPid.toBase58() });
sig = await op.methods.deposit(new BN(20_000_000)).accountsPartial({ vault, owner: owner.publicKey }).signers([owner]).rpc();
log({ step: 'deposit', ok: true, sig, lamports: 20_000_000 });
const memo = new anchor.BorshInstructionCoder(swapIdl).encode('swap_log', { memo: Buffer.from('lab swap 3_000_000') });
const hook = (amt, signer = agent, target = swapPid, to = recipient.publicKey, data = memo) => program(idl, signer).methods.executeHook(new BN(amt), data).accountsPartial({ agent: signer.publicKey, vault, targetProgram: target, recipient: to }).remainingAccounts([{ pubkey: target, isSigner: false, isWritable: false }]).signers([signer]).rpc();
sig = await hook(3_000_000);
log({ step: 'execute_hook', ok: true, sig, recipient_lamports: await conn.getBalance(recipient.publicKey), cpi: 'mock_swap.swap_log' });
await expectFail('hook_over_limit', () => hook(6_000_000));
await expectFail('hook_wrong_target', () => hook(1_000_000, agent, SystemProgram.programId, recipient.publicKey, Buffer.alloc(0)));
await expectFail('hook_wrong_agent', () => hook(1_000_000, stranger));
await expectFail('hook_recipient_is_vault', () => hook(1_000_000, agent, swapPid, vault));
await expectFail('update_policy_by_stranger', () => program(idl, stranger).methods.updatePolicy(stranger.publicKey, new BN(10_000_000_000), swapPid).accountsPartial({ vault, owner: stranger.publicKey }).signers([stranger]).rpc());
sig = await op.methods.updatePolicy(agent.publicKey, new BN(1_000_000), swapPid).accountsPartial({ vault, owner: owner.publicKey }).signers([owner]).rpc();
log({ step: 'update_policy', ok: true, sig, spend_limit: 1_000_000 });
await expectFail('hook_over_new_limit', () => hook(2_000_000));
const v = await prog.account.firewallPolicy.fetch(vault);
log({ step: 'state', spend_limit: v.spendLimit.toString(), vault_lamports: await conn.getBalance(vault) });
process.exit(0);
