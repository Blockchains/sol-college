import fs from 'fs';
import { Keypair, PublicKey, SystemProgram } from '@solana/web3.js';
import { payer, conn, log, program, fund, expectFail, sendIx, BN } from './lib/labcommon.mjs';
const idl = JSON.parse(fs.readFileSync(new URL('../../dapps/static/agent-reputation/idl.json', import.meta.url), 'utf8'));
const prog = program(idl);
const pid = new PublicKey(idl.address);
const pda = (...s) => PublicKey.findProgramAddressSync(s.map(x => typeof x === 'string' ? Buffer.from(x) : x), pid)[0];
const worker = Keypair.generate(), stranger = Keypair.generate();
await fund(worker.publicKey, 10_000_000); await fund(stranger.publicKey, 5_000_000);
const counter = pda('job_counter');
log({ step: 'setup', program: pid.toBase58(), worker: worker.publicKey.toBase58(), counter: counter.toBase58() });
let sig;
if (!(await conn.getAccountInfo(counter))) { sig = await prog.methods.initializeCounter().accountsPartial({ jobCounter: counter, payer: payer.publicKey }).rpc(); log({ step: 'initialize_counter', ok: true, sig }); }
const wp = pda('profile', worker.publicKey.toBuffer());
sig = await program(idl, worker).methods.initializeProfile().accountsPartial({ profile: wp, authority: worker.publicKey }).signers([worker]).rpc();
log({ step: 'initialize_profile', ok: true, sig, profile: wp.toBase58() });
const now = Math.floor(Date.now() / 1000);
const nextJob = async () => pda('job', new BN((await prog.account.jobCounter.fetch(counter)).count).toArrayLike(Buffer, 'le', 8));
const hash = Array(32).fill(7);
await expectFail('create_job_payment_too_small', async () => prog.methods.createJob(hash, new BN(500_000), new BN(now + 3600), worker.publicKey).accountsPartial({ job: await nextJob(), jobCounter: counter, client: payer.publicKey }).rpc());
let job = await nextJob();
sig = await prog.methods.createJob(hash, new BN(5_000_000), new BN(now + 3600), worker.publicKey).accountsPartial({ job, jobCounter: counter, client: payer.publicKey }).rpc();
log({ step: 'create_job', ok: true, sig, job: job.toBase58(), escrow_lamports: 5_000_000 });
await expectFail('accept_by_non_whitelisted', () => program(idl, stranger).methods.acceptJob().accountsPartial({ job, worker: stranger.publicKey }).signers([stranger]).rpc());
sig = await program(idl, worker).methods.acceptJob().accountsPartial({ job, worker: worker.publicKey }).signers([worker]).rpc();
log({ step: 'accept_job', ok: true, sig });
await expectFail('cancel_accepted_job', () => prog.methods.cancelJob().accountsPartial({ job, client: payer.publicKey }).rpc());
const rating = pda('rating', job.toBuffer());
await expectFail('complete_rating_6', () => prog.methods.completeJob(6, true, hash).accountsPartial({ job, rating, workerProfile: wp, worker: worker.publicKey, client: payer.publicKey }).rpc());
await expectFail('complete_by_stranger', () => program(idl, stranger).methods.completeJob(5, true, hash).accountsPartial({ job, rating, workerProfile: wp, worker: worker.publicKey, client: stranger.publicKey }).signers([stranger]).rpc());
const wb = await conn.getBalance(worker.publicKey);
sig = await prog.methods.completeJob(5, true, hash).accountsPartial({ job, rating, workerProfile: wp, worker: worker.publicKey, client: payer.publicKey }).rpc();
log({ step: 'complete_job', ok: true, sig, worker_received: (await conn.getBalance(worker.publicKey)) - wb });
sig = await prog.methods.getReputation().accountsPartial({ profile: wp }).rpc();
log({ step: 'get_reputation', ok: true, sig });
job = await nextJob();
sig = await prog.methods.createJob(hash, new BN(2_000_000), new BN(now + 3600), null).accountsPartial({ job, jobCounter: counter, client: payer.publicKey }).rpc();
log({ step: 'create_job_open', ok: true, sig, job: job.toBase58() });
sig = await prog.methods.cancelJob().accountsPartial({ job, client: payer.publicKey }).rpc();
log({ step: 'cancel_job', ok: true, sig });
job = await nextJob();
sig = await prog.methods.createJob(hash, new BN(2_000_000), new BN(now + 3600), null).accountsPartial({ job, jobCounter: counter, client: payer.publicKey }).rpc();
log({ step: 'create_job_3', ok: true, sig, job: job.toBase58() });
sig = await program(idl, worker).methods.acceptJob().accountsPartial({ job, worker: worker.publicKey }).signers([worker]).rpc();
log({ step: 'accept_job_3', ok: true, sig });
sig = await program(idl, worker).methods.disputeJob().accountsPartial({ job, disputer: worker.publicKey }).signers([worker]).rpc();
log({ step: 'dispute_job', ok: true, sig });
await expectFail('resolve_before_7_days', () => prog.methods.resolveDispute().accountsPartial({ job, workerProfile: wp, client: payer.publicKey, worker: worker.publicKey, resolver: payer.publicKey }).rpc());
const p = await prog.account.agentProfile.fetch(wp);
log({ step: 'state', completed_jobs: p.completedJobs, total_rating_points: p.totalRatingPoints, on_time: p.onTimeCount });
sig = await sendIx([SystemProgram.transfer({ fromPubkey: worker.publicKey, toPubkey: payer.publicKey, lamports: 5_000_000 })], [payer, worker]);
log({ step: 'cleanup_return_worker_payment', sig });
process.exit(0);
