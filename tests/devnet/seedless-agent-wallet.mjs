import fs from 'fs';
import { Keypair, PublicKey, SystemProgram } from '@solana/web3.js';
import { payer, conn, log, program, fund, expectFail, BN } from './lib/labcommon.mjs';
const idl = JSON.parse(fs.readFileSync(new URL('../../dapps/static/seedless-agent-wallet/idl.json', import.meta.url), 'utf8'));
const prog = program(idl);
const pid = new PublicKey(idl.address);
const agent = Keypair.generate(), dest = Keypair.generate(), stranger = Keypair.generate();
const [vault] = PublicKey.findProgramAddressSync([Buffer.from('vault'), payer.publicKey.toBuffer(), agent.publicKey.toBuffer()], pid);
log({ step: 'setup', program: pid.toBase58(), vault: vault.toBase58(), agent: agent.publicKey.toBase58(), destination: dest.publicKey.toBase58() });
await fund(agent.publicKey, 5_000_000); await fund(stranger.publicKey, 5_000_000);
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
let sig = await prog.methods.createVault(new BN(10_000_000), new BN(25_000_000), 3).accounts({ authority: payer.publicKey, agent: agent.publicKey, vault, systemProgram: SystemProgram.programId }).rpc();
log({ step: 'create_vault', ok: true, sig, max_per_tx: 10_000_000, max_daily: 25_000_000, cooldown: 3 });
sig = await prog.methods.deposit(new BN(50_000_000)).accounts({ depositor: payer.publicKey, vault, systemProgram: SystemProgram.programId }).rpc();
log({ step: 'deposit', ok: true, sig, lamports: 50_000_000 });
const ag = program(idl, agent);
const w = (amt, signer = agent, p = ag) => p.methods.agentWithdraw(new BN(amt)).accounts({ vault, agent: signer.publicKey, destination: dest.publicKey }).signers([signer]).rpc();
sig = await w(10_000_000);
log({ step: 'agent_withdraw', ok: true, sig, destination_lamports: await conn.getBalance(dest.publicKey) });
await expectFail('withdraw_during_cooldown', () => w(1_000_000));
await expectFail('withdraw_over_per_tx', () => w(20_000_000));
await sleep(4500);
sig = await w(10_000_000);
log({ step: 'agent_withdraw_2', ok: true, sig, destination_lamports: await conn.getBalance(dest.publicKey) });
await sleep(4500);
await expectFail('withdraw_over_daily', () => w(10_000_000));
await expectFail('withdraw_by_stranger', () => w(1_000_000, stranger, program(idl, stranger)));
sig = await prog.methods.emergencyStop().accounts({ vault, authority: payer.publicKey }).rpc();
log({ step: 'emergency_stop', ok: true, sig });
await expectFail('withdraw_after_stop', () => w(1_000_000));
const before = await conn.getBalance(payer.publicKey);
sig = await prog.methods.drainVault().accounts({ vault, authority: payer.publicKey, destination: payer.publicKey }).rpc();
log({ step: 'drain_vault', ok: true, sig, returned_lamports: (await conn.getBalance(payer.publicKey)) - before });
const v = await prog.account.agentVault.fetch(vault);
log({ step: 'state', total_spent: v.totalSpent.toString(), tx_count: v.txCount.toString(), is_active: v.policy.isActive });
process.exit(0);
